"""Freeze the current results/ into a dated, committed snapshot under docs/.

    python -m scripts.run_ablation      # produce results/ (gitignored)
    python -m scripts.snapshot_results  # freeze them into docs/results/ (committed)

Why this exists: `results/` is deliberately gitignored, because it is
regenerated output and committing it invites hand-editing. But a report needs
numbers that stay put -- if you quote MAP 0.409 in Review 1 and later change the
scorer, you need to be able to point at exactly which run produced that figure.

So: results/ is the working directory, docs/results/ is the record. Snapshots
are immutable by convention -- never edit one after taking it. If the numbers
change, take a new snapshot; the old one stays as the provenance for whatever
you already wrote.
"""

from __future__ import annotations

import argparse
import json
import shutil
from datetime import date
from pathlib import Path

RESULTS_DIR = Path("results")
DOCS_RESULTS = Path("docs/results")

#: Files copied verbatim into the snapshot.
ARTEFACTS = ("ablation.md", "config.json")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--label",
        default=date.today().isoformat(),
        help="Snapshot directory name (default: today's date).",
    )
    parser.add_argument(
        "--note",
        default="",
        help="One line on what changed since the last snapshot.",
    )
    parser.add_argument(
        "--force", action="store_true", help="Overwrite an existing snapshot."
    )
    args = parser.parse_args()

    missing = [f for f in ARTEFACTS if not (RESULTS_DIR / f).exists()]
    if missing:
        print(
            f"Missing {', '.join(missing)} in {RESULTS_DIR}/.\n"
            "Run `python -m scripts.run_ablation` first."
        )
        return 1

    target = DOCS_RESULTS / args.label
    if target.exists() and not args.force:
        print(f"{target} already exists. Use --label <name> or --force.")
        return 1

    target.mkdir(parents=True, exist_ok=True)
    for name in ARTEFACTS:
        shutil.copy2(RESULTS_DIR / name, target / name)

    # A short README per snapshot so the directory is self-describing six weeks
    # from now, when nobody remembers what "2026-07-30" was.
    config = json.loads((target / "config.json").read_text(encoding="utf-8"))
    corpus = config.get("corpus", {})
    results = config.get("results", {})
    best = max(results, key=lambda r: results[r]["MAP"]) if results else "n/a"

    # List items rather than bare lines: markdown collapses consecutive plain
    # lines into one paragraph, which would run these three together.
    lines = [
        f"# Results snapshot -- {args.label}",
        "",
        f"- Model: `{config.get('model', '?')}`, top_k {config.get('top_k', '?')}",
        f"- Corpus: {corpus.get('requirements', '?')} requirements, "
        f"{corpus.get('nodes', '?')} nodes, {corpus.get('files', '?')} files, "
        f"{corpus.get('gold_links', '?')} gold links",
    ]
    if results:
        lines.append(f"- Best MAP: **{best}** ({results[best]['MAP']:.3f})")
    lines.append("")
    if args.note:
        lines += [f"**Note:** {args.note}", ""]
    lines += [
        "Generated by `python -m scripts.snapshot_results`. Do not edit -- take a",
        "new snapshot instead, so previously-reported figures keep their provenance.",
        "",
        "See `ablation.md` for the table and `config.json` for the full run log.",
        "",
    ]
    (target / "README.md").write_text("\n".join(lines), encoding="utf-8")

    print(f"Snapshot written to {target}/")
    for name in (*ARTEFACTS, "README.md"):
        print(f"  {name}")
    commit_cmd = (
        f"git add {target.as_posix()} && git commit -m 'Snapshot results {args.label}'"
    )
    print(f"\nCommit it:\n  {commit_cmd}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
